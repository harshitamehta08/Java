public class Displaying {
    public static void main(String[] args) {
        System.out.println("screen display");
        for (int i = 0; i <= 9; i++){
            for (int j = 1; j <= i; j++)
                {
                    System.out.println(" ");
                    System.out.println(i);
                }
                System.out.println("\n");
        }
        System.out.println("screen display is done");
    }
}
